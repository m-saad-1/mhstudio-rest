import fs from "node:fs/promises";
import path from "node:path";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = fileURLToPath(new URL("../", import.meta.url));
const output = path.join(root, "public/optimized");
const manifestFile = path.join(root, "src/data/responsive-images.ts");
const settings = { widths: [384, 640, 768, 1024, 1200, 1536], avif: { quality: 55, effort: 5 }, webp: { quality: 75, effort: 5 } };
const sources = {
  // Keep source filename casing exact: Vercel builds on Linux, where paths are case-sensitive.
  "device-showcase": "Device-showcase.avif",
  "web-and-app": "WebAndApp.avif",
  "rms-dashboard": "restaurant-management-dashboard-workspace.avif",
  pos: "restaurant-pos.avif",
  "online-ordering": "online-ordering.avif",
  kds: "modern-kitchen-display-system-showcase.avif",
  "dine-in": "modern-restaurant-table-management-dashboard.avif",
  "qr-menu": "qr-menu.avif",
  "site-logo": { file: "../mh_logo.png", widths: [48, 96, 144] },
  whatsapp: { file: "whatsapp.avif", widths: [40, 80, 120] },
};

await fs.mkdir(output, { recursive: true });
const images = {};
let generated = 0;
for (const [name, source] of Object.entries(sources)) {
  const filename = typeof source === "string" ? source : source.file;
  const candidateWidths = typeof source === "string" ? settings.widths : source.widths;
  const encoding = { ...settings, widths: candidateWidths };
  const bytes = await fs.readFile(path.join(root, "public/images", filename));
  const hash = createHash("sha256").update(bytes).update(JSON.stringify(encoding)).digest("hex").slice(0, 12);
  const { width, height } = await sharp(bytes).metadata();
  if (!width || !height) throw new Error(`Missing image dimensions: ${filename}`);
  const widths = [...new Set([...candidateWidths.filter((w) => w < width), Math.min(width, candidateWidths[candidateWidths.length - 1])])];
  const formats = {};
  for (const format of ["avif", "webp"]) {
    const variants = [];
    for (const size of widths) {
      const filename = `${name}-${hash}-${size}.${format}`;
      const destination = path.join(output, filename);
      try { await fs.access(destination); }
      catch {
        await sharp(bytes).rotate().resize({ width: size, withoutEnlargement: true }).toFormat(format, settings[format]).toFile(destination);
        generated += 1;
      }
      variants.push({ width: size, src: `/optimized/${filename}` });
    }
    formats[format] = variants;
  }
  images[name] = { width, height, ...formats };
}

const manifest = `// Generated by scripts/generate-responsive-images.mjs; do not edit by hand.\nexport const responsiveImages = ${JSON.stringify(images, null, 2)} as const;\n\nexport type ResponsiveImageName = keyof typeof responsiveImages;\n`;
let previous = "";
try { previous = await fs.readFile(manifestFile, "utf8"); } catch { /* First generation. */ }
if (previous !== manifest) await fs.writeFile(manifestFile, manifest);
console.log(`Responsive images ready (${Object.keys(images).length} sources; ${generated} files generated).`);
